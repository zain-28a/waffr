#!/usr/bin/env python3
"""Generates the PBKDF2-HMAC-SHA256 test vectors shared by the Dart, Kotlin and
Swift tests, and the app's runtime self-test (NATIVE_PBKDF2_PLAN.md).

Outputs come from Python's hashlib (OpenSSL), an implementation independent of
the app's three, so a vector cannot pass just because two of them share a bug.
Passwords are given as UTF-8 bytes (hex), exactly what the app derives from:
utf8.encode() of the Dart string, never normalised.

    python3 tool/gen_pbkdf2_vectors.py          # rewrite every copy
    python3 tool/gen_pbkdf2_vectors.py --check  # exit 1 if a copy is stale
"""

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JSON_COPIES = (
    ROOT / "test/fixtures/pbkdf2_vectors.json",
    ROOT / "android/app/src/test/resources/pbkdf2_vectors.json",
)
SWIFT_FILE = ROOT / "ios/RunnerTests/RunnerTests.swift"
SWIFT_BEGIN = "  // BEGIN GENERATED PBKDF2 VECTORS (tool/gen_pbkdf2_vectors.py)"
SWIFT_END = "  // END GENERATED PBKDF2 VECTORS"
DART_FILE = ROOT / "lib/core/security/pbkdf2.dart"
DART_BEGIN = "// BEGIN GENERATED SELF-TEST VECTORS (tool/gen_pbkdf2_vectors.py)"
DART_END = "// END GENERATED SELF-TEST VECTORS"
BENCH_FILE = ROOT / "tool/kdf_benchmark_vectors.dart"
# The runtime self-test uses the cheap vectors: a few milliseconds natively.
SELF_TEST_MAX_ITERATIONS = 4096

SALT16 = bytes(range(16))
SALT32 = bytes(range(100, 132))

# (name, password text or raw bytes, salt, iterations)
CASES = [
    ("rfc7914", "passwd", b"salt", 1),
    ("ascii-1", "password", b"salt", 1),
    ("ascii-2", "password", b"salt", 2),
    ("ascii-4096", "password", b"salt", 4096),
    ("arabic", "كلمة سر عربية ١٢٣", SALT16, 1000),
    ("arabic-salt32", "مرحبا بالعالم", SALT32, 1000),
    ("emoji", "emoji 🔐👍🏽 pass", SALT16, 1000),
    ("long-100-bytes", "x" * 100, SALT16, 1000),
    ("long-mixed", "طويلة " * 20 + "🔐" * 10, SALT16, 3),
    ("exactly-64-bytes", "k" * 64, SALT16, 5),
    ("empty", "", SALT16, 10),
    ("unnormalised-nfd", "é vs é", SALT16, 7),
    ("app-210000", "correct horse 1", SALT16, 210_000),
    ("app-600000", "correct horse 1", SALT16, 600_000),
    ("app-arabic-210000", "كلمة المرور ٢٠٢٦", SALT32, 210_000),
]


def vectors() -> list[dict]:
    out = []
    for name, password, salt, iterations in CASES:
        raw = password.encode("utf-8")
        derived = hashlib.pbkdf2_hmac("sha256", raw, salt, iterations, 32)
        out.append(
            {
                "name": name,
                "password_hex": raw.hex(),
                "salt_hex": salt.hex(),
                "iterations": iterations,
                "derived_hex": derived.hex(),
            }
        )
    return out


def json_text(items: list[dict]) -> str:
    return json.dumps({"algorithm": "pbkdf2-hmac-sha256", "length": 32, "vectors": items}, indent=2) + "\n"


def swift_block(items: list[dict]) -> str:
    lines = [SWIFT_BEGIN, "  static let vectors: [(name: String, password: String, salt: String, iterations: Int, derived: String)] = ["]
    for item in items:
        lines.append(
            f'    ("{item["name"]}", "{item["password_hex"]}", "{item["salt_hex"]}", '
            f'{item["iterations"]}, "{item["derived_hex"]}"),'
        )
    lines += ["  ]", SWIFT_END]
    return "\n".join(lines)


def replace_block(current: str, begin: str, end_marker: str, block: str) -> str:
    start = current.index(begin)
    end = current.index(end_marker) + len(end_marker)
    return current[:start] + block + current[end:]


def swift_text(current: str, items: list[dict]) -> str:
    return replace_block(current, SWIFT_BEGIN, SWIFT_END, swift_block(items))


def dart_block(items: list[dict]) -> str:
    lines = [DART_BEGIN, "// dart format off", "final List<Pbkdf2Vector> selfTestVectors = ["]
    for item in items:
        if item["iterations"] > SELF_TEST_MAX_ITERATIONS:
            continue
        lines += [
            "  Pbkdf2Vector(",
            f"    '{item['name']}',",
            f"    _hex('{item['password_hex']}'),",
            f"    _hex('{item['salt_hex']}'),",
            f"    {item['iterations']},",
            f"    _hex('{item['derived_hex']}'),",
            "  ),",
        ]
    lines += ["];", "// dart format on", DART_END]
    return "\n".join(lines)


def bench_text(items: list[dict]) -> str:
    lines = [
        "// GENERATED by tool/gen_pbkdf2_vectors.py; do not edit.",
        "// dart format off",
        "// Every shared PBKDF2 vector, for the on-device check in kdf_benchmark.dart.",
        "",
        "/// (name, password hex, salt hex, iterations, derived hex)",
        "const List<(String, String, String, int, String)> benchmarkVectors = [",
    ]
    for item in items:
        lines.append(
            f"  ('{item['name']}', '{item['password_hex']}', '{item['salt_hex']}', "
            f"{item['iterations']}, '{item['derived_hex']}'),"
        )
    lines += ["];", "// dart format on"]
    return "\n".join(lines) + "\n"


def dart_text(current: str, items: list[dict]) -> str:
    return replace_block(current, DART_BEGIN, DART_END, dart_block(items))


def main() -> int:
    items = vectors()
    wanted = {path: json_text(items) for path in JSON_COPIES}
    wanted[SWIFT_FILE] = swift_text(SWIFT_FILE.read_text(), items)
    wanted[DART_FILE] = dart_text(DART_FILE.read_text(), items)
    wanted[BENCH_FILE] = bench_text(items)
    check = "--check" in sys.argv
    stale = [path for path, text in wanted.items() if not path.exists() or path.read_text() != text]
    if check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        return 1 if stale else 0
    for path, text in wanted.items():
        path.write_text(text)
    print(f"wrote {len(items)} vectors to {len(wanted)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
